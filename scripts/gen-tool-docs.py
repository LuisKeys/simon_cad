#!/usr/bin/env python3
"""Regenerates docs/tools.md from the live tool registry (`simoncad-cli tools --json`)."""
import json
import subprocess
import sys

HEADER = """# Tool reference

Everything the agent, the CLI and (later) the UI can do goes through these tools. This file is
generated by `make docs` from the live registry (`simoncad-cli tools --json`), so the schemas below
are exact. Do not edit by hand.

**Pipeline per call:** unknown-tool check → strict JSON decode → JSON-schema validation (unknown
arguments are rejected) → semantic validation → *edit* tools return a plan of commands that becomes a
ChangeSet; *query* tools return data directly. Errors are written to be actionable (they are fed
back to the model). All tools currently belong to the `geometry` capability.

Common optional arguments on feature-creating tools: `id` (lowercase letters / digits / underscores;
generated from `name` or the type if omitted), `name` (human-readable), `intent` (the engineering
intent in natural language, stored on the node).

Invoke directly with: `simoncad-cli tool <project> <tool> '<json>'`.
"""


def typ(p):
    t = p.get("type", "any")
    if "enum" in p:
        return " \\| ".join(map(str, p["enum"]))
    if t == "array":
        it = p.get("items", {})
        return "array of " + (typ(it) if it.get("type") != "array" else "array")
    extra = ""
    if "exclusiveMinimum" in p:
        extra = " > %g" % p["exclusiveMinimum"]
    if "minimum" in p:
        extra = " ≥ %g" % p["minimum"]
    if "maximum" in p and t == "integer":
        extra += " ≤ %g" % p["maximum"]
    return t + extra


def main():
    cli = sys.argv[1] if len(sys.argv) > 1 else "./out/simoncad-cli"
    tools = json.loads(subprocess.check_output([cli, "tools", "--json"]))["tools"]
    out = [HEADER]
    for kind, title in (("edit", "Edit tools (produce a ChangeSet)"), ("query", "Query tools (no model change)")):
        out.append("\n## %s\n" % title)
        for t in tools:
            if t["mutating"] != (kind == "edit"):
                continue
            s = t["schema"]
            req = set(s.get("required", []))
            out.append("### `%s`\n\n%s\n" % (t["name"], t["description"]))
            props = s.get("properties", {})
            if not props:
                out.append("_No arguments._\n")
                continue
            out.append("| Argument | Type | Required | Description |\n|---|---|---|---|")
            for k, p in props.items():
                if k in ("id", "name", "intent") and k not in req and t["name"] != "modify_parameter":
                    continue
                desc = p.get("description", "").replace("|", "\\|")
                out.append("| `%s` | %s | %s | %s |" % (k, typ(p), "yes" if k in req else "", desc))
            out.append("")
    with open("docs/tools.md", "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
