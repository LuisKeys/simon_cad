const okGcode = `; generated by FakeSlicer 1.0
M83
G1 X10 Y10 Z0.3 F6000
;LAYER_CHANGE
;TYPE:External perimeter
G1 X20 Y10 E0.5 F1800
G1 X20 Y20 E0.5
`

// fake writes an executable shell script standing in for the slicer.
func fake(t *testing.T, body string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "prusa-slicer")
	script := "#!/bin/sh\nALL=\"$*\"\nout=\"\"\nwhile [ $# -gt 0 ]; do case \"$1\" in --output) out=\"$2\"; shift;; esac; shift; done\n" + body
	if err := os.WriteFile(p, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	return p
}

func input(t *testing.T) slicing.Input {
	dir := t.TempDir()
	stl := filepath.Join(dir, "model.stl")
	os.WriteFile(stl, []byte("x"), 0o600)
	return slicing.Input{STLPath: stl, WorkDir: dir}
}

func TestSliceParsesOutput(t *testing.T) {
	s := &Slicer{Path: fake(t, "cat > \"$out\" <<'EOF'\n"+okGcode+"EOF\n")}
	res, err := s.Slice(context.Background(), input(t), profile.GenericFDM())
	if err != nil {
		t.Fatal(err)
	}
	if res.Provider != "prusaslicer" || len(res.Segments) != 3 || res.Segments[1].Kind != toolpath.ExternalPerimeter {
		t.Fatalf("%+v", res)
	}
}

func TestSliceInvocationIsIsolated(t *testing.T) {
	argsFile := filepath.Join(t.TempDir(), "args")
	t.Setenv("FAKE_ARGS", argsFile)
	s := &Slicer{Path: fake(t, "echo \"$ALL\" > \"$FAKE_ARGS\"\ncat > \"$out\" <<'EOF'\n"+okGcode+"EOF\n")}
	in := input(t)
	if _, err := s.Slice(context.Background(), in, profile.GenericFDM()); err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(argsFile)
	args := string(b)
	for _, want := range []string{"--export-gcode", "--dont-arrange", "--datadir " + in.WorkDir, "--load " + in.WorkDir + "/profile.ini", in.STLPath} {
		if !strings.Contains(args, want) {
			t.Errorf("args %q missing %q", args, want)
		}
	}
}

func TestSliceFailureCarriesSlicerOutput(t *testing.T) {
	s := &Slicer{Path: fake(t, "echo 'Error: the object is not manifold' >&2\nexit 3\n")}
	_, err := s.Slice(context.Background(), input(t), profile.GenericFDM())
	if err == nil || !strings.Contains(err.Error(), "not manifold") {
		t.Fatalf("the slicer's message must reach the user: %v", err)
	}
}

