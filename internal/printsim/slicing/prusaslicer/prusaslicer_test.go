func TestSliceRejectsUnsafeG(t *testing.T) {
	// the slicer's G-code is untrusted: an inch-mode file must fail, not be mis-scaled
	s := &Slicer{Path: fake(t, "printf 'G20\\nG1 X1 Y1\\n' > \"$out\"\n")}
	_, err := s.Slice(context.Background(), input(t), profile.GenericFDM())
	if err == nil || !strings.Contains(err.Error(), "G20") {
		t.Fatalf("%v", err)
	}
}

func alive(pid int) bool { return syscall.Kill(pid, 0) == nil }

func waitDead(t *testing.T, pid int) {
	t.Helper()
	for i := 0; i < 100; i++ {
		if !alive(pid) {
			return
		}
		time.Sleep(20 * time.Millisecond)
	}
	t.Fatalf("process %d survived cancellation", pid)
}

func pidFrom(t *testing.T, file string) int {
	t.Helper()
	for i := 0; i < 200; i++ {
		if b, err := os.ReadFile(file); err == nil {
			if n, err := strconv.Atoi(strings.TrimSpace(string(b))); err == nil {
				return n
			}
		}
		time.Sleep(10 * time.Millisecond)
	}
	t.Fatal("the fake slicer never started")
	return 0
}

func TestCancelKillsTheWholeProcessTree(t *testing.T) {
	pidFile := filepath.Join(t.TempDir(), "pid")
	t.Setenv("FAKE_PID", pidFile)
	// a child that would outlive a plain kill of the parent shell
	s := &Slicer{Path: fake(t, "sleep 60 &\necho $! > \"$FAKE_PID\"\nwait\n")}
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan error, 1)
	in := input(t)
	go func() { _, err := s.Slice(ctx, in, profile.GenericFDM()); done <- err }()
	child := pidFrom(t, pidFile)
	if !alive(child) {
		t.Fatal("child should be running")
	}
	cancel()
	select {
	case err := <-done:
		if !errors.Is(err, context.Canceled) {
			t.Fatalf("want context.Canceled, got %v", err)
		}
	case <-time.After(10 * time.Second):
		t.Fatal("Slice did not return after cancellation")
	}
	waitDead(t, child)
}

func TestTimeoutStopsTheSlicer(t *testing.T) {
	s := &Slicer{Path: fake(t, "sleep 60\n"), Timeout: 200 * time.Millisecond}
	start := time.Now()
	_, err := s.Slice(context.Background(), input(t), profile.GenericFDM())
	if err == nil || !strings.Contains(err.Error(), "did not finish") {
		t.Fatalf("%v", err)
	}
	if time.Since(start) > 8*time.Second {
		t.Fatal("timeout was not enforced")
	}
}

func TestLocate(t *testing.T) {
	if err := (&Slicer{Path: "/definitely/not/here"}).Available(); !errors.Is(err, slicing.ErrUnavailable) {
		t.Fatalf("%v", err)
	}
	notExec := filepath.Join(t.TempDir(), "x")
	os.WriteFile(notExec, []byte("hi"), 0o600)
	if err := (&Slicer{Path: notExec}).Available(); err == nil || !strings.Contains(err.Error(), "not an executable") {
		t.Fatalf("%v", err)
	}
	if err := (&Slicer{Path: fake(t, "")}).Available(); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", t.TempDir())
	err := (&Slicer{}).Available()
	if !errors.Is(err, slicing.ErrUnavailable) || !strings.Contains(err.Error(), "preview slicer") {
		t.Fatalf("a missing slicer needs an actionable message: %v", err)
	}
}

func TestConfigContents(t *testing.T) {
	p := profile.GenericFDM()
	p.InfillPct = 35
	p.Supports = true
	p.Adhesion = profile.AdhesionBrim
	c := Config(p)
	for _, want := range []string{
		"bed_shape = 0x0,220x0,220x220,0x220", "nozzle_diameter = 0.4", "fill_density = 35%", "layer_height = 0.2",
		"support_material = 1", "brim_width = 5", "skirts = 0", "use_relative_e_distances = 1", "layer_gcode = G92 E0", "perimeters = 2",
		"max_print_height = 250", "temperature = 210", "bed_temperature = 60", "fill_pattern = rectilinear",
	} {
		if !strings.Contains(c, want+"\n") {
			t.Errorf("config missing %q:\n%s", want, c)
		}
	}
	if !strings.Contains(c, "not verified hardware") {
		t.Error("config must say it is a simulation profile")
	}
}

