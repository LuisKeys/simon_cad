package prusaslicer

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/accelone/simoncad/internal/printsim/profile"
)

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

// Config renders the profile as a PrusaSlicer .ini. Every value is a number or a value from
// a closed set validated by profile.Validate, so nothing user-supplied reaches the file as
// free text.
func Config(p profile.PrintProfile) string {
	v := p.PrintSpeed
	pat := string(p.InfillPat)
	brim, skirts := 0.0, 0
	switch p.Adhesion {
	case profile.AdhesionBrim:
		brim = 5
	case profile.AdhesionSkirt:
		skirts = 1
	}
	kv := [][2]string{
		{"bed_shape", fmt.Sprintf("0x0,%sx0,%sx%s,0x%s", num(p.BuildX), num(p.BuildX), num(p.BuildY), num(p.BuildY))},
		{"max_print_height", num(p.BuildZ)},
		{"nozzle_diameter", num(p.NozzleDiameter)},
		{"filament_diameter", num(p.FilamentDiameter)},
		{"filament_density", num(p.FilamentDensity)},
		{"temperature", num(p.PrintTemp)},
		{"first_layer_temperature", num(p.PrintTemp)},
		{"bed_temperature", num(p.BedTemp)},
		{"first_layer_bed_temperature", num(p.BedTemp)},
		{"layer_height", num(p.LayerHeight)},
		{"first_layer_height", num(p.LayerHeight)},
		{"perimeters", strconv.Itoa(p.Walls)},
		{"top_solid_layers", strconv.Itoa(p.TopBottomLay)},
		{"bottom_solid_layers", strconv.Itoa(p.TopBottomLay)},
		{"fill_density", num(p.InfillPct) + "%"},
		{"fill_pattern", pat},
		{"perimeter_speed", num(v)},
		{"small_perimeter_speed", num(v * 0.7)},
		{"external_perimeter_speed", num(v * 0.7)},
		{"infill_speed", num(v)},
		{"solid_infill_speed", num(v * 0.8)},
		{"top_solid_infill_speed", num(v * 0.6)},
		{"support_material_speed", num(v)},
		{"bridge_speed", num(v * 0.6)},
		{"gap_fill_speed", num(v * 0.6)},
		{"first_layer_speed", num(v * 0.5)},
		{"travel_speed", num(p.TravelSpeed)},
		{"max_print_speed", num(max(100, v))},
		{"max_volumetric_speed", "0"},
		{"support_material", b(p.Supports)},
		{"support_material_auto", "1"},
		{"brim_width", num(brim)},
		{"skirts", strconv.Itoa(skirts)},
		{"skirt_height", "1"},
		{"skirt_distance", "3"},
		// plain, single-extruder Marlin-style output with relative extrusion, so the
		// simulation's G-code interpreter sees M83 / G1 E…
		{"gcode_flavor", "marlin2"},
		{"use_relative_e_distances", "1"},
		{"use_firmware_retraction", "0"},
		{"retract_length", "0.8"},
		{"binary_gcode", "0"},
		{"gcode_comments", "0"},
		// PrusaSlicer refuses relative extrusion unless E is reset on every layer
		{"layer_gcode", "G92 E0"},
		{"start_gcode", "G90"},
		{"end_gcode", "M104 S0"},
	}
	var sb strings.Builder
	sb.WriteString("# generated by SimonCAD print simulation — simulation profile, not verified hardware\n")
	for _, e := range kv {
		sb.WriteString(e[0] + " = " + e[1] + "\n")
	}
	return sb.String()
}

func b(v bool) string {
	if v {
		return "1"
	}
	return "0"
}
